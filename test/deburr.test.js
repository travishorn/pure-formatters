const combiningMarks = [
  ...codePointRange(0x0300, 0x036f),
  ...codePointRange(0xfe20, 0xfe23),
];

test("converts Latin Unicode letters to basic Latin", () => {
  expect(burredLetters.map((letter) => deburr(letter))).toEqual(
    deburredLetters,
  );
});

test("does not deburr Latin mathematical operators", () => {
  const operators = ["\xd7", "\xf7"];

  expect(operators.map((operator) => deburr(operator))).toEqual(operators);
});

test("deburrs combining diacritical marks", () => {
  expect(combiningMarks.map((mark) => deburr(`e${mark}i`))).toEqual(
    combiningMarks.map(() => "ei"),
  );
});
